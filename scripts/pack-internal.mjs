import { mkdirSync, readFileSync } from 'node:fs';
import { resolve } from 'node:path';
import { execFileSync } from 'node:child_process';
const root = process.cwd();
const pkg = JSON.parse(readFileSync(resolve(root, 'package.json'), 'utf8'));
if (!pkg.private || !pkg.version.includes('-internal.')) throw new Error('This command is only for private internal builds. Public publication requires a separate explicit release decision.');
const output = resolve(root, '.docsy/packages');
mkdirSync(output, { recursive: true });
const [artifact] = JSON.parse(execFileSync('npm', ['pack', '--ignore-scripts', '--json', '--cache', resolve(output, '.npm-cache'), '--pack-destination', output], { cwd: root, encoding: 'utf8', maxBuffer: 20 * 1024 * 1024 }));
const file = resolve(output, artifact.filename);
console.log(`Internal package: ${file}\n\nCreate a site without publishing anything:\nnpm exec --package ${JSON.stringify(file)} -- create-docsy my-docs --yes --ci\n\nOptional Pages scaffold: add --deploy github-pages --repo https://github.com/OWNER/REPOSITORY\nDeployment remains gated by DOCSY_ENABLE_PAGES. This command never publishes to npm or GitHub.`);
